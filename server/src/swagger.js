import swaggerUi from "swagger-ui-express";

const json = { "application/json": {} };

function operation(summary, tag, extra = {}) {
  return { tags: [tag], summary, responses: { 200: { description: "OK" } }, ...extra };
}

const spec = {
  openapi: "3.0.3",
  info: {
    title: "MeetAI local API",
    version: "2.0.0",
    description:
      "Local-first meeting assistant. Runs entirely on the user's machine: MongoDB for metadata, the filesystem for recordings/transcripts/notes, Whisper for speech to text and Ollama + Llama 3 for analysis. Gmail, Notion and Gemini are optional."
  },
  servers: [{ url: "/api/v1" }],
  paths: {
    "/meetings": {
      get: operation("List meetings (search, filter, sort, paginate)", "Meetings", {
        parameters: [
          { name: "scope", in: "query", schema: { type: "string", enum: ["today", "upcoming", "previous", "recorded"] } },
          { name: "status", in: "query", schema: { type: "string" } },
          { name: "search", in: "query", schema: { type: "string" } },
          { name: "page", in: "query", schema: { type: "integer" } },
          { name: "limit", in: "query", schema: { type: "integer" } }
        ]
      }),
      post: operation("Create a meeting manually", "Meetings", { requestBody: { content: json } })
    },
    "/meetings/{id}": {
      get: operation("Meeting detail with tasks, job and file availability", "Meetings"),
      patch: operation("Update a meeting", "Meetings"),
      delete: operation("Soft-delete a meeting", "Meetings")
    },
    "/meetings/{id}/recording": { get: operation("Stream the local MP4 (HTTP range supported)", "Meetings") },
    "/meetings/{id}/transcript": { get: operation("Read or download the local transcript", "Meetings") },
    "/meetings/{id}/notes": { get: operation("Markdown meeting notes generated by the local model", "Meetings") },
    "/meetings/{id}/start": { post: operation("Join the meeting now with the persistent browser profile and start recording", "Automation") },
    "/meetings/{id}/stop": { post: operation("Stop recording, leave the call and queue processing", "Automation") },
    "/meetings/{id}/process": { post: operation("Queue transcription, AI analysis and Notion sync in the background", "Automation") },
    "/meetings/{id}/job": { get: operation("Latest background job for this meeting", "Automation") },
    "/tasks": {
      get: operation("List tasks", "Tasks"),
      post: operation("Create a task", "Tasks")
    },
    "/tasks/{id}": {
      patch: operation("Update a task", "Tasks"),
      delete: operation("Delete a task", "Tasks")
    },
    "/analytics": { get: operation("Local analytics overview", "Analytics") },
    "/system/status": { get: operation("Health of MongoDB, Ollama, Whisper, FFmpeg, Gmail and Notion", "System") },
    "/system/settings": {
      get: operation("Effective local settings", "System"),
      patch: operation("Update the editable local settings", "System")
    },
    "/system/audio-devices": { get: operation("FFmpeg capture devices (Windows dshow)", "System") },
    "/integrations/gmail/connect": { post: operation("Return the Google OAuth consent URL", "Integrations") },
    "/integrations/gmail/callback": { get: operation("OAuth redirect target", "Integrations") },
    "/integrations/gmail/status": { get: operation("Gmail connection status", "Integrations") },
    "/integrations/gmail/sync": { post: operation("Scan Gmail for meeting invitations now", "Integrations") },
    "/integrations/notion/status": { get: operation("Notion configuration status", "Integrations") },
    "/integrations/browser/connect": { post: operation("Open the persistent browser profile to sign in to Google once", "Integrations") },
    "/integrations/browser/status": { get: operation("Whether the local browser profile has a Google session", "Integrations") }
  }
};

export function setupSwagger(app) {
  app.use("/api-docs", swaggerUi.serve, swaggerUi.setup(spec, { explorer: true }));
  app.get("/api-docs.json", (_req, res) => res.json(spec));
}
